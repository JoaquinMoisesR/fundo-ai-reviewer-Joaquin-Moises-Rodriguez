"""One command: keyword engine -> LLM reviewer -> evaluation -> credit impact -> report.

  python src/run.py             uses the cache; calls Claude only for missing entries
                                (needs ANTHROPIC_API_KEY and `pip install -r requirements.txt`)
  python src/run.py --offline   cache only, no key, no network, stdlib only
  python src/run.py --input their.json
                                review transactions someone else brings (no ground truth):
                                engine labels, reviewer flags, underwriter queue, offers
                                before/after -> output/input_report.md

Writes output/report.md (human-readable) and output/results.json (everything).
"""
import argparse
import json
import sys
from pathlib import Path

import credit_impact
import evaluate
import keyword_engine
import reviewer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "output"


def money(x):
    return f"{x:,.0f}"


def render(review, ev, credit, sim):
    L = []
    w = L.append
    w("# Results\n")
    w(f"Generated by `python src/run.py`. Model `{review['model']}`, prompt `{review['prompt_version']}`, "
      f"engine `{keyword_engine.ENGINE_VERSION}`. Tokens in/out: {review['tokens']['input']:,} / "
      f"{review['tokens']['output']:,}. Estimated cost of the cached run: US${review['cost_usd']:.2f}.\n")

    w("## 1. Reviewer\n")
    f = ev["flags"]
    w("| | Legacy engine | After reviewer |\n|---|---:|---:|")
    for k in ("label_errors", "material_errors", "material_dollars"):
        w(f"| {k.replace('_', ' ')} | {money(ev['legacy'][k])} | {money(ev['reviewed'][k])} |")
    w("")
    w(f"- Patterns reviewed: {f['patterns_total']} (from 1,785 transactions); flagged: {f['patterns_flagged']}; "
      f"unreviewed (invalid output / outage): {f['patterns_unreviewed']}.")
    w(f"- Transactions flagged: {f['tx_flagged']} ({f['tx_flagged_correctly']} legacy really wrong, "
      f"{f['tx_false_flags']} false flags).")
    w(f"- Material flags (would move revenue or a feature; the only ones an underwriter sees): "
      f"{f['patterns_flagged_material']} patterns / {f['tx_material_flags']} tx; {f['tx_material_flags_correct']} fix a "
      f"material legacy error, {f['tx_material_false_flags']} are on a correct label.")
    w(f"- **Hard negatives flagged: {f['hard_negatives_flagged']} of {f['hard_negatives']} "
      f"({f['hard_negatives_flagged_material']} reach the underwriter).**")
    w(f"- Material legacy errors caught: {f['legacy_material_errors_flagged']} of {f['legacy_material_errors']}.")
    w(f"- Corrections applied (confidence >= {reviewer.THRESHOLD_RAISES_OFFER} if it raises the offer, "
      f">= {reviewer.THRESHOLD_LOWERS_OFFER} if it lowers it): {f['applied_corrections_tx']} tx, "
      f"{f['applied_corrections_right']} match the truth.")
    w(f"- Transactions routed to an underwriter (flag or suspicious text): {f['tx_routed_to_human']}.\n")

    w("### Monthly revenue dollar error per business (label - truth)\n")
    w("| Business | True monthly revenue | Legacy error | Reviewed error |\n|---|---:|---:|---:|")
    for r in ev["revenue"]:
        w(f"| {r['business_id']} | {money(r['truth'])} | {r['legacy_error']:+,.0f} | {r['reviewed_error']:+,.0f} |")
    tl = sum(abs(r["legacy_error"]) for r in ev["revenue"])
    tr = sum(abs(r["reviewed_error"]) for r in ev["revenue"])
    w(f"| **sum of absolute errors** | | **{money(tl)}** | **{money(tr)}** |\n")

    w("### Adversarial descriptions\n")
    w("| Description | Truth | Legacy | Proposed | Model saw injection | Code saw injection | Final correct |\n|---|---|---|---|---|---|---|")
    for a in ev["adversarial"]:
        prop = a["proposed"]["group"] if a["proposed"] else "-"
        w(f"| `{a['description'][:70]}` | {a['truth_group']} | {a['legacy']['group']} | {prop} | "
          f"{a['model_injection_flag']} | {a['code_injection_flag']} | {a['final_correct']} |")
    w("")

    w("### Reviewer mistakes (read these)\n")
    if not ev["mistakes"]:
        w("None.\n")
    for m in ev["mistakes"]:
        prop = f"{m['proposed']['group']}/{'biz' if m['proposed']['is_business'] else 'personal'}" if m["proposed"] else "-"
        w(f"- **{m['kind']}** - {m['business_id']} `{m['description'][:70]}` x{m['count']} "
          f"(${money(m['total'])}): legacy {m['legacy']['group']}, proposed {prop}, truth {m['truth']['group']}"
          f"{' - ' + m['reason'] if m['reason'] else ''}")
    w("")

    w("## 2. Credit impact (legacy -> reviewed -> truth)\n")
    w("| Business | Revenue share | NSF / OD | High-risk share of debits | Funder $/day | Offer legacy | Offer reviewed | Offer truth |\n|---|---|---|---|---|---:|---:|---:|")
    for r in credit:
        lg, rv, tr = r["legacy"], r["reviewed"], r["truth"]
        w(f"| {r['business_id']} | {lg['revenue_share']:.0%} / {rv['revenue_share']:.0%} / {tr['revenue_share']:.0%} "
          f"| {lg['nsf_count']}/{lg['od_count']} -> {rv['nsf_count']}/{rv['od_count']} -> {tr['nsf_count']}/{tr['od_count']} "
          f"| {lg['high_risk_share']:.1%} / {rv['high_risk_share']:.1%} / {tr['high_risk_share']:.1%} "
          f"| {lg['funder_daily']:.0f} / {rv['funder_daily']:.0f} / {tr['funder_daily']:.0f} "
          f"| {money(lg['offer'])} | {money(rv['offer'])} | {money(tr['offer'])} |")
    w("")
    w("### Mislabel simulation (true labels corrupted at a rate; 200 runs x 10 businesses)\n")
    w("| Error type | Rate | Mean offer change | Mean abs offer change | Decision flips | Monthly revenue change | Funder $/day change | NSF change |\n|---|---:|---:|---:|---:|---:|---:|---:|")
    for s in sim:
        w(f"| {s['scenario']} | {s['rate']:.0%} | {s['mean_offer_change']:+,.0f} | {money(s['mean_abs_offer_change'])} "
          f"| {s['decision_flip_rate']:.1%} | {s['mean_monthly_revenue_change']:+,.0f} | {s['mean_funder_daily_change']:+,.1f} "
          f"| {s['mean_nsf_change']:+.2f} |")
    w("")
    return "\n".join(L)


def load_input(path: Path) -> list:
    """Accept three shapes and return our list-of-businesses shape.

    1. our format: [{"business_id", "transactions": [...]}, ...]
    2. a Plaid /transactions/get response: {"accounts": [...], "transactions": [...]}
    3. a bare list of Plaid transactions
    Shapes 2 and 3 are grouped by account_id (one account = one business).
    """
    raw = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(raw, list) and raw and "transactions" in raw[0]:
        businesses = raw
    else:
        txs = raw["transactions"] if isinstance(raw, dict) else raw
        by_acct = {}
        for t in txs:
            by_acct.setdefault(t.get("account_id", "acct"), []).append(t)
        businesses = [{"business_id": a, "business_name": a, "institution": "unknown",
                       "account_id": a, "transactions": ts} for a, ts in by_acct.items()]
    for b in businesses:
        b.setdefault("business_name", b["business_id"])
        b.setdefault("institution", "unknown")
        for i, t in enumerate(b["transactions"]):
            missing = [k for k in ("date", "amount", "name") if k not in t]
            if missing:
                sys.exit(f"{b['business_id']} transaction #{i}: missing {missing}")
            t.setdefault("transaction_id", f"{b['business_id']}-{i:04d}")
            t["amount"] = float(t["amount"])
        b["transactions"].sort(key=lambda t: t["date"])
    return businesses


def render_input(review, credit):
    L = []
    w = L.append
    w("# Review of supplied transactions\n")
    w(f"Model `{review['model']}`, prompt `{review['prompt_version']}`. No ground truth, so no accuracy "
      f"numbers: this is what an underwriter would see. Cost of this run: US${review['cost_usd']:.2f}.\n")
    w("## Offer, legacy labels vs reviewed labels\n")
    w("| Business | Window days | Monthly revenue | NSF / OD | Funder $/day | High-risk share | Offer |\n|---|---:|---|---|---|---|---|")
    for r in credit:
        lg, rv = r["legacy"], r["reviewed"]
        w(f"| {r['business_id']} | {r['window_days']} | {money(lg['monthly_revenue'])} -> {money(rv['monthly_revenue'])} "
          f"| {lg['nsf_count']}/{lg['od_count']} -> {rv['nsf_count']}/{rv['od_count']} "
          f"| {lg['funder_daily']:.0f} -> {rv['funder_daily']:.0f} "
          f"| {lg['high_risk_share']:.1%} -> {rv['high_risk_share']:.1%} | {money(lg['offer'])} -> {money(rv['offer'])} |")
    w("")
    w("## Underwriter queue (material flags and suspicious text)\n")
    w("| Business | Description | n | Total $ | Legacy | Proposed | Conf. | Applied | Injection | Reason |\n|---|---|---:|---:|---|---|---:|---|---|---|")
    for res in review["results"]:
        for p in res["patterns"]:
            if not p.get("needs_human"):
                continue
            inj = p.get("model_injection_flag") or p["code_injection_flag"]
            w(f"| {p['business_id']} | `{p['description'][:60]}` | {p['count']} | {money(p['total'])} "
              f"| {p['legacy']['group']}{'' if p['legacy']['is_business'] else ' (personal)'} "
              f"| {p['proposed']['group']}{'' if p['proposed']['is_business'] else ' (personal)'} "
              f"| {p['confidence']:.2f} | {p['applied']} | {inj} | {p['reason']} |")
    w("")
    unrev = [(r["business_id"], r["status"], r["problems"]) for r in review["results"]
             if r["status"] != "ok" or r["problems"]]
    if unrev:
        w("## Not fully reviewed (legacy labels kept)\n")
        for b, st, pr in unrev:
            w(f"- {b}: {st} {pr}")
    return "\n".join(L)


def run_input(path: Path, offline: bool):
    businesses = load_input(path)
    legacy = {k: {kk: v[kk] for kk in ("group", "is_business", "is_revenue")}
              for k, v in keyword_engine.label_all(businesses).items()}
    try:
        review = reviewer.review_all(businesses, legacy, offline=offline)
    except reviewer.CacheMiss as e:
        sys.exit(f"cache miss: {e}")
    credit = credit_impact.table(businesses, {"legacy": legacy, "reviewed": review["labels"]})
    for row, b in zip(credit, businesses):
        row["window_days"] = reviewer.window_days(b["transactions"])
    OUT.mkdir(exist_ok=True)
    report = render_input(review, credit)
    (OUT / "input_report.md").write_text(report, encoding="utf-8")
    print(report)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true", help="use the committed cache only")
    ap.add_argument("--input", type=Path, help="review a transactions file that has no ground truth")
    args = ap.parse_args()
    if args.input:
        return run_input(args.input, args.offline)

    data = ROOT / "data"
    businesses = json.loads((data / "transactions.json").read_text())
    truth = json.loads((data / "truth.json").read_text())

    legacy = {k: {kk: v[kk] for kk in ("group", "is_business", "is_revenue")}
              for k, v in keyword_engine.label_all(businesses).items()}
    try:
        review = reviewer.review_all(businesses, legacy, offline=args.offline)
    except reviewer.CacheMiss as e:
        sys.exit(f"cache miss: {e}")
    for r in review["results"]:
        if r["status"] != "ok" or r["problems"]:
            print(f"[warn] {r['business_id']}: {r['status']} {r['problems']}")

    ev = evaluate.evaluate(businesses, truth, legacy, review)
    credit = credit_impact.table(businesses, {"legacy": legacy, "reviewed": review["labels"], "truth": truth})
    sim = credit_impact.simulate(businesses, truth)

    OUT.mkdir(exist_ok=True)
    report = render(review, ev, credit, sim)
    (OUT / "report.md").write_text(report, encoding="utf-8")
    slim = {k: v for k, v in review.items() if k != "labels"}
    (OUT / "results.json").write_text(json.dumps(
        {"review": slim, "evaluation": ev, "credit": credit, "simulation": sim}, indent=1, default=str),
        encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
